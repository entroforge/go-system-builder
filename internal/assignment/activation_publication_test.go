func TestActivationFamiliesPreserveUnknownPaths(t *testing.T) {
	for _, family := range []string{"envelope", "activation", "work_start"} {
		for _, occupant := range []string{"root_file", "root_symlink", "ancestor_symlink", "same_bytes", "different_bytes", "directory"} {
			t.Run(family+"/"+occupant, func(t *testing.T) {
				root := t.TempDir()
				source := ActivationSourceEntry{AgentID: "agent-safe", WritePaths: []string{"src/"}}
				publish := func() (string, error) {
					switch family {
					case "envelope":
						ref, err := PreStageActivationEnvelope(root, "wg-safe", "TASK-safe", "agent-safe", "plan_checkpoint", source)
						if err != nil {
							return "", err
						}
						return filepath.Join(root, filepath.FromSlash(ref)), nil
					case "activation":
						return WriteActivationMessageFile(root, "wg-safe", "TASK-safe", "agent-safe", map[string]any{"agent_id": "agent-safe"})
					default:
						return WriteWorkStartMessageFile(root, "wg-safe", "TASK-safe", "agent-safe", "agents/builder.md", "team-safe", "loop-safe", "act-safe", "corr-safe", -1, "2026-11-10T00:00:00Z")
					}
				}
				// Obtain the exact generated bytes in a separate clean fixture, then
				// remove this known test object before installing an unknown occupant.
				preferred, err := publish()
				if err != nil {
					t.Fatal(err)
				}
				original, err := os.ReadFile(preferred)
				if err != nil {
					t.Fatal(err)
				}
				if err := os.RemoveAll(filepath.Join(root, ".claude", "evidence")); err != nil {
					t.Fatal(err)
				}
				occupied := preferred
				unknown := []byte("unknown original")
				var target string
				switch occupant {
				case "root_file":
					occupied = filepath.Join(root, ".claude", "evidence")
				case "root_symlink", "ancestor_symlink":
					target = t.TempDir()
					if err := os.WriteFile(filepath.Join(target, "unknown.txt"), unknown, 0600); err != nil {
						t.Fatal(err)
					}
					occupied = filepath.Join(root, ".claude", "evidence")
					if occupant == "ancestor_symlink" {
						occupied = filepath.Join(occupied, "wg-safe")
						if err := os.MkdirAll(filepath.Dir(occupied), 0700); err != nil {
							t.Fatal(err)
						}
					}
					if err := os.Symlink(target, occupied); err != nil {
						t.Skipf("symlink unavailable: %v", err)
					}
				case "same_bytes":
					unknown = original
				}
				if target == "" {
					if err := os.MkdirAll(filepath.Dir(occupied), 0700); err != nil {
						t.Fatal(err)
					}
					if occupant == "directory" {
						if err := os.Mkdir(occupied, 0700); err != nil {
							t.Fatal(err)
						}
					} else if err := os.WriteFile(occupied, unknown, 0600); err != nil {
						t.Fatal(err)
					}
				}
				actual, err := publish()
				if err != nil {
					t.Fatal(err)
				}
				rel, err := filepath.Rel(root, actual)
				if err != nil {
					t.Fatal(err)
				}
				if !strings.HasPrefix(filepath.ToSlash(rel), ".claude/evidence-alt-") {
					t.Fatalf("actual path = %s", rel)
				}
				got, err := os.ReadFile(actual)
				if err != nil || !bytes.Equal(got, original) {
					t.Fatalf("published bytes: %q, %v", got, err)
				}
				if target != "" {
					dest, err := os.Readlink(occupied)
					if err != nil || dest != target {
						t.Fatalf("symlink changed: %q %v", dest, err)
					}
					entries, err := os.ReadDir(target)
					if err != nil || len(entries) != 1 {
						t.Fatalf("unknown target changed: %v %v", entries, err)
					}
				} else if occupant == "directory" {
					entries, err := os.ReadDir(occupied)
					if err != nil || len(entries) != 0 {
						t.Fatalf("unknown directory changed: %v %v", entries, err)
					}
				} else {
					got, err := os.ReadFile(occupied)
					if err != nil || !bytes.Equal(got, unknown) {
						t.Fatalf("unknown changed: %q %v", got, err)
					}
				}
				if family == "envelope" {
					got, err := ResolveAgentActivationEnvelope(root, filepath.ToSlash(rel))
					if err != nil || len(got.WritePaths) != 1 || got.WritePaths[0] != "src/" {
						t.Fatalf("actual envelope unreadable: %#v %v", got, err)
					}
				}
			})
		}
	}
}

func TestActivationPublicationDoesNotAdoptConcurrentCandidates(t *testing.T) {
	root := t.TempDir()
	const publishers = 8
	var wg sync.WaitGroup
	paths := make(chan string, publishers)
	for i := 0; i < publishers; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			ref, err := PreStageActivationEnvelope(root, "wg-safe", "TASK-safe", "agent-safe", "plan_checkpoint", ActivationSourceEntry{AgentID: "agent-safe"})
			if err != nil {
				t.Error(err)
				return
			}
			paths <- ref
		}()
	}
	wg.Wait()
	close(paths)
	seen := map[string]bool{}
	for ref := range paths {
		if seen[ref] {
			t.Fatalf("unregistered candidate adopted: %s", ref)
		}
		seen[ref] = true
	}
	if len(seen) != publishers {
		t.Fatalf("got %d candidates", len(seen))
	}
}
